"""Portfolio artefact: one-page evidence of the data-preprocessing work.

Panels (all computed from the pipeline's own outputs):
  A  missingness per raw diabetes-130 column, and what was done about it
  B  exclusions applied to diabetes-130, with counts
  C  why encounters had to be split by patient (encounters per patient; overlap = 0)
  D  the planned-care artifact found in the Synthea data (days to next admission)

Output: figures/evidence_preprocessing.png
Usage:  python src/preprocessing_evidence.py
"""
import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

import config as C  # noqa: E402
import models as MD  # noqa: E402
from figures import AXIS, BLUE, INK2, MUTED, ORANGE, SURFACE  # noqa: E402,F401

ACTION = {"weight": "dropped", "medical_specialty": "not a shared feature",
          "payer_code": "audit attribute only", "race": "'Unknown' group",
          "diag_3": "no flag set", "diag_2": "no flag set", "diag_1": "no flag set"}


def main():
    miss = pd.read_csv(C.RESULTS / "d130_missingness.csv", index_col=0).pct_missing
    flow = json.loads((C.RESULTS / "cohort_flow_d130.json").read_text())
    d130 = pd.read_parquet(C.DATA_PROCESSED / "d130.parquet")
    syn = pd.read_parquet(C.DATA_PROCESSED / "synthea_incl_planned.parquet")

    fig, ax = plt.subplots(2, 2, figsize=(11, 8))
    fig.suptitle("Evidence of data preprocessing: 30-day readmission project",
                 fontsize=13, fontweight="bold", x=0.01, ha="left")

    # A: missingness
    a = ax[0, 0]
    m = miss.sort_values()
    a.barh(m.index, m.values, color=BLUE, height=0.6)
    for i, (k, v) in enumerate(m.items()):
        a.text(v + 1, i, f"{v:.1f}%  → {ACTION.get(k, '')}", va="center", fontsize=8)
    a.set_xlim(0, 150); a.set_xlabel("% missing ('?' in raw file)")
    a.set_title("A. Missing values and how each was handled", loc="left", fontsize=10)

    # B: exclusions
    b = ax[0, 1]
    labels = ["Raw encounters"] + [r["step"].split(":")[1].split("(")[0].strip()
                                   for r in flow[1:-1]] + ["Analysis cohort"]
    values = [flow[0]["encounters"]] + [-r["excluded"] for r in flow[1:-1]] + \
             [flow[-1]["encounters"]]
    colors = [BLUE] + [ORANGE] * (len(values) - 2) + [BLUE]
    y = np.arange(len(values))[::-1]
    b.barh(y, [abs(v) for v in values], color=colors, height=0.6)
    for yi, v in zip(y, values):
        b.text(abs(v) + 1500, yi, f"{v:+,}" if v < 0 else f"{v:,}", va="center", fontsize=8)
    b.set_yticks(y); b.set_yticklabels(labels, fontsize=8); b.set_xscale("log")
    b.set_xlim(1, 1e6); b.set_xlabel("encounters (log scale)")
    b.set_title("B. Exclusions applied (diabetes-130)", loc="left",
                fontsize=10)

    # C: patients with several encounters -> grouped split
    c = ax[1, 0]
    per = d130.patient_id.value_counts()
    bins = [1, 2, 3, 4, 5, 10, 41]
    counts = pd.cut(per, bins=bins, right=False).value_counts().sort_index()
    names = ["1", "2", "3", "4", "5-9", "10+"]
    c.bar(names, counts.values, color=BLUE)
    tr, te = MD.grouped_split(d130.y, d130.patient_id, C.TEST_FRACTION_FOLDS, C.SEED)
    overlap = len(set(d130.patient_id.iloc[tr]) & set(d130.patient_id.iloc[te]))
    multi = (per > 1).sum()
    c.set_yscale("log"); c.set_xlabel("encounters per patient"); c.set_ylabel("patients")
    c.set_title("C. Repeat patients: why the split is grouped by patient", loc="left",
                fontsize=10)
    c.text(0.98, 0.95, f"{multi:,} patients have >1 encounter\n"
                       f"({(d130.patient_id.map(per) > 1).mean():.0%} of encounters)\n"
                       f"patients in both train and test: {overlap}",
           transform=c.transAxes, ha="right", va="top", fontsize=9,
           bbox=dict(fc="white", ec=AXIS))

    # D: planned-care artifact in Synthea
    d = ax[1, 1]
    dd = syn.dropna(subset=["days_to_next_admit"])
    dd = dd[dd.days_to_next_admit <= 90]
    edges = np.arange(0, 91, 5)
    d.hist([dd.days_to_next_admit[dd.planned], dd.days_to_next_admit[~dd.planned]],
           bins=edges, stacked=True, color=[ORANGE, BLUE],
           label=[f"planned care, n={int(syn.planned.sum()):,}",
                  f"unplanned, n={int((~syn.planned).sum()):,}"])
    d.axvline(30, color=INK2, lw=1.2)
    d.text(31, d.get_ylim()[1] * 0.55, "30-day\nlabel\ncut-off", fontsize=8)
    d.set_xlabel("days from discharge to next admission (Synthea)")
    d.set_ylabel("index stays"); d.legend(fontsize=7.5, loc="upper right", frameon=False)
    d.set_title("D. QA finding: planned cycles cluster at 30 days", loc="left",
                fontsize=10)

    for axx in ax.flat:
        axx.spines[["top", "right"]].set_visible(False)
    fig.text(0.01, 0.005, "Generated by src/preprocessing_evidence.py from results/ and "
             "data/processed/ (commit history shows the planned-care amendment was "
             "made before any external evaluation).", fontsize=8, color=MUTED)
    fig.tight_layout(rect=(0, 0.02, 1, 0.96))
    out = C.FIGURES / "evidence_preprocessing.png"
    fig.savefig(out, dpi=180, facecolor=SURFACE)
    print("saved", out, "| overlap", overlap)


if __name__ == "__main__":
    main()
